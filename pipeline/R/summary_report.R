    paras <- c(paras, sprintf("Every module carries a distinct function: %s. Module size ranges from %s to %s proteins.",
                              sr_join(sprintf("M%s (%s proteins; %s)", tb$module, tb$n_proteins,
                                              sr_cut(tb$top_function, 45)), 10L),
                              sr_int(min(tb$n_proteins)), sr_int(max(tb$n_proteins))))
  }
  list(paragraphs = paras, tables = tabs)
}

