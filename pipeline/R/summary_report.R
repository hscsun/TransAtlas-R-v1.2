# Small readers and formatters
# ---------------------------------------------------------------------------
sr_read <- function(dir, file) {
  if (is.null(file) || is.na(file)) return(NULL)
  path <- file.path(dir, file)
  if (!file.exists(path)) return(NULL)
  tryCatch(utils::read.csv(path, stringsAsFactors = FALSE, check.names = FALSE),
           error = record_optional_error)
}

# First file in `dir` matching a regular expression, or NA.
sr_pick <- function(dir, pattern) {
  f <- list.files(dir, pattern, full.names = FALSE)
  if (length(f)) f[1] else NA_character_
}

sr_num <- function(x, digits = 2) {
  x <- suppressWarnings(as.numeric(x))
  if (!length(x) || all(is.na(x))) return("—")
  formatC(x, format = "f", digits = digits, big.mark = ",")
}

sr_int <- function(x) {
  x <- suppressWarnings(as.numeric(x))
  if (!length(x) || all(is.na(x))) return("—")
  formatC(round(x), format = "d", big.mark = ",")
}

# Columns read back from CSV can arrive as character (a stray label, a quoted
# number, a locale-specific decimal mark). Every value that enters a math call
# goes through this coercion first, so one malformed cell cannot abort the
# whole report.
sr_numvec <- function(x) suppressWarnings(as.numeric(x))

sr_p <- function(x) {
  x <- suppressWarnings(as.numeric(x))
  if (!length(x) || all(is.na(x))) return("—")
  ifelse(x < 1e-4, formatC(x, format = "e", digits = 2), formatC(x, format = "f", digits = 4))
}

# Join up to `n` names with commas, appending "and" before the last item.
sr_join <- function(x, n = 8L) {
  x <- as.character(x)
  x <- x[!is.na(x) & nzchar(x)]
  if (!length(x)) return("—")
  x <- utils::head(x, n)
  if (length(x) == 1L) return(x)
  paste0(paste(utils::head(x, -1L), collapse = ", "), " and ", utils::tail(x, 1L))
}

# First entries of a " / "-separated list, as produced in top_GO_BP columns.
sr_first <- function(x, n = 2) {
  if (is.null(x) || !length(x) || is.na(x) || !nzchar(x)) return("—")
  parts <- trimws(strsplit(as.character(x), " / ", fixed = TRUE)[[1]])
  sr_join(parts[nzchar(parts)], n)
}

sr_cut <- function(x, n = 90) {
  x <- as.character(x)
  ifelse(is.na(x), "—",
         ifelse(nchar(x) > n, paste0(substr(x, 1, n - 1), "…"), x))
}

# "name (value)" list used to enumerate terms with their gene counts.
sr_with_counts <- function(name, value, n = 8L, digits = 0L) {
  name <- as.character(name); value <- suppressWarnings(as.numeric(value))
  k <- min(length(name), n)
  if (!k) return("—")
  vals <- if (digits > 0L) formatC(value[seq_len(k)], format = "f", digits = digits, big.mark = ",") else
    formatC(round(value[seq_len(k)]), format = "d", big.mark = ",")
  paste0(name[seq_len(k)], " (", vals, ")", collapse = ", ")
}

