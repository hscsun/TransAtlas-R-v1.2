                                            sr_join(gsub("^HALLMARK_", "", dn$pathway), 5L)))
  }
  if (length(rows)) tabs[[length(tabs) + 1L]] <- sr_tbl(
    "Table 10. Leading activated and repressed gene sets by source", do.call(rbind, rows))
  list(paragraphs = paras, tables = tabs)
}

