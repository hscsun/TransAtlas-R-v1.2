# Fixed-template result report.
#
# After every analysis run this module fills one fixed template with the results
# of that run: gene counts, enriched biological functions, regulation trends,
# key genes, TF modules and protein-interaction modules. The template itself is
# an R object (SUMMARY_TEMPLATE below); sections are always emitted in the same
# order and with the same field names, so two runs produce directly comparable
# reports. Output is a Word document plus a machine-readable values table.
#
# The module reads the tables the pipeline already wrote under results/<data>/;
# it never re-runs an analysis. render_summary_report() is called at the end of
# run_pipeline() and can also be called on its own through
# scripts/build_summary_report.R.

