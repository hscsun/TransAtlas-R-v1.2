    tb <- s$gsea_terms[[ont]]
    up <- tb[tb$NES > 0, , drop = FALSE]; up <- utils::head(up[order(-up$NES), , drop = FALSE], 3L)
    dn <- tb[tb$NES < 0, , drop = FALSE]; dn <- utils::head(dn[order(dn$NES), , drop = FALSE], 3L)
    for (x in list(up, dn)) {
      if (!nrow(x)) next
      rows[[length(rows) + 1L]] <- data.frame(
        `Source` = ont, `Direction` = ifelse(x$NES > 0, "Activated", "Repressed"),
        `Gene set` = x$Description, `NES` = sr_num(x$NES, 2), `Adjusted P` = sr_p(x$p.adjust),
        check.names = FALSE)
    }
    if (nrow(up)) {
      paras <- c(paras, sprintf("The most strongly activated %s programmes are %s, with normalised enrichment scores of %s.",
                                ont, sr_join(up$Description, 5L), sr_join(sr_num(up$NES, 2), 5L)))
    }
    if (nrow(dn)) {
      paras <- c(paras, sprintf("The most strongly repressed %s programmes are %s (NES %s).",
                                ont, sr_join(dn$Description, 5L), sr_join(sr_num(dn$NES, 2), 5L)))
    }
  }
  if (!is.null(s$msigdb) && nrow(s$msigdb)) {
    tb <- s$msigdb
    up <- tb[tb$NES > 0, , drop = FALSE]; up <- utils::head(up[order(-up$NES), , drop = FALSE], 5L)
    dn <- tb[tb$NES < 0, , drop = FALSE]; dn <- utils::head(dn[order(dn$NES), , drop = FALSE], 5L)
    for (x in list(up, dn)) {
      if (!nrow(x)) next
      rows[[length(rows) + 1L]] <- data.frame(
        `Source` = "MSigDB Hallmark", `Direction` = ifelse(x$NES > 0, "Activated", "Repressed"),
        `Gene set` = gsub("^HALLMARK_", "", x$pathway), `NES` = sr_num(x$NES, 2),
        `Adjusted P` = sr_p(x$padj), check.names = FALSE)
    }
    if (nrow(up)) paras <- c(paras, sprintf("Among the Hallmark collection the activated programmes are %s, with NES between %s and %s.",
                                            sr_join(gsub("^HALLMARK_", "", up$pathway), 5L),
                                            sr_num(min(up$NES), 2), sr_num(max(up$NES), 2)))
