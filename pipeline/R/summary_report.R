  out <- data.frame(
    `Module` = tb$module, `TFs` = as.integer(tb$n_tfs),
    `Members` = sr_cut(tb$tfs, 70),
    `Target union (up/down)` = sprintf("%d (%d/%d)", tb$n_targets_union,
                                 tb$n_up_union, tb$n_down_union),
    `Representative TF` = tb$representative,
    `Leading GO BP` = sr_cut(vapply(tb$representative_top_GO_BP, sr_first, character(1)), 55),
    check.names = FALSE)
  tabs[[length(tabs) + 1L]] <- sr_tbl("Table 20. TF modules", out)
  paras <- c(paras, sprintf("Clustering TFs on the Jaccard overlap of their differentially expressed targets produces %s modules. %s.",
                            sr_int(nrow(tb)),
                            sr_join(sprintf("%s (%s TFs, representative %s, leading function %s)",
                                            tb$module, tb$n_tfs, tb$representative,
                                            vapply(tb$representative_top_GO_BP, sr_first, character(1))), 8L)))
  if (nrow(tb)) {
    paras <- c(paras, sprintf("Module sizes range from %s to %s TFs, and the union of targets ranges from %s to %s genes. Modules with a shared function indicate coordinated regulation by several TFs rather than independent effects.",
                              sr_int(min(tb$n_tfs)), sr_int(max(tb$n_tfs)),
                              sr_int(min(tb$n_targets_union)), sr_int(max(tb$n_targets_union))))
