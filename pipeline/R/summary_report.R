}

sr_add_heading <- function(doc, text, size = 14) {
  fpar <- officer::fpar(
    officer::ftext(text, officer::fp_text(font.family = "Arial", font.size = size,
                                          bold = TRUE, color = "grey10")),
    fp_p = officer::fp_par(
      padding.top = 10, padding.bottom = 3, keep_with_next = TRUE,
      border.bottom = officer::fp_border(color = "grey60", width = 0.75)))
  officer::body_add_fpar(doc, fpar)
}

sr_add_table <- function(doc, caption, data) {
  if (is.null(data) || !nrow(data)) return(doc)
  doc <- sr_add_par(doc, caption, size = 9, bold = TRUE, colour = "grey30", keep = TRUE)
  ft <- flextable::flextable(data)
  ft <- flextable::font(ft, fontname = "Times New Roman", part = "all")
  ft <- flextable::fontsize(ft, size = 9, part = "all")
  ft <- flextable::bold(ft, part = "header")
  ft <- flextable::bg(ft, bg = "#EFEFEF", part = "header")
  ft <- flextable::theme_booktabs(ft)
  ft <- flextable::padding(ft, padding.top = 1.2, padding.bottom = 1.2, part = "all")
  ft <- flextable::line_spacing(ft, space = 0.95, part = "all")
  # Explicit widths: automatic layout measures text unreliably and can collapse
  # the first column. Weight each column by its widest cell or header and cap
  # the weight so one long text column cannot starve the others.
  w <- vapply(seq_along(data), function(j) {
    x <- as.character(data[[j]])
    max(c(4, nchar(x, type = "width"),
          nchar(names(data)[j], type = "width")), na.rm = TRUE)
  }, numeric(1))
  total <- 6.3
  w <- pmin(w, 30)
  w <- w / sum(w) * total
  min_w <- 0.7
  w <- pmax(w, min_w)
  if (sum(w) > total) {
    over <- sum(w) - total
    room <- w - min_w
    if (sum(room) > 0) w <- w - over * room / sum(room)
  }
  ft <- flextable::width(ft, j = seq_along(w), width = w)
  ft <- flextable::set_table_properties(ft, layout = "fixed")
  # Small tables stay on one page instead of splitting by a single row.
  if (nrow(data) <= 12L) ft <- flextable::keep_with_next(ft, i = seq_len(nrow(data)))
  doc <- flextable::body_add_flextable(doc, ft)
  sr_add_par(doc, "", size = 4)
}

# Native aspect ratio of an appendix figure, capped to the text block.
sr_img_size <- function(path, max_w = 6.2, max_h = 6.6) {
  dims <- tryCatch({
    if (requireNamespace("magick", quietly = TRUE)) {
      info <- magick::image_info(magick::image_read(path))
      c(info$width[1], info$height[1])
    } else c(1600, 1200)
  }, error = function(e) c(1600, 1200))
  ar <- dims[2] / dims[1]
  w <- max_w; h <- w * ar
  if (h > max_h) { h <- max_h; w <- h / ar }
  c(width = w, height = h)
}

# A flat table of every value that went into the report, for downstream reuse.
summary_value_table <- function(s, blocks) {
  rows <- list()
  for (b in blocks) {
    for (t in b$tables) {
      d <- t$data
      if (is.null(d) || !nrow(d)) next
      rows[[length(rows) + 1L]] <- data.frame(
        section = rep(b$title, nrow(d)),
        table = rep(sub("^Table [0-9]+\\.\\s*", "", t$caption), nrow(d)),
        item = as.character(d[[1]]),
        value = if (ncol(d) > 1L) {
          apply(d[, -1, drop = FALSE], 1, function(r) paste(r, collapse = " | "))
        } else rep("", nrow(d)),
        stringsAsFactors = FALSE)
    }
  }
  if (!length(rows)) return(NULL)
  do.call(rbind, rows)
}

render_summary_report <- function(cfg, results_dir, out_dir,
                                  template = SUMMARY_TEMPLATE,
                                  file_name = "results_report.docx") {
  missing_writers <- c("officer", "flextable")[
    !vapply(c("officer", "flextable"), requireNamespace, logical(1), quietly = TRUE)]
  if (length(missing_writers)) {
    stop("The Word report needs the package(s) ",
         paste(missing_writers, collapse = " and "), ", which could not be loaded.\n",
         "  Install them with BiocManager::install(c(\"officer\", \"flextable\")).\n",
         if (.Platform$OS.type == "unix" && Sys.info()[["sysname"]] == "Darwin")
           "  On macOS, run `xcode-select --install` first: flextable depends on systemfonts/textshaping, which need a C++ toolchain.\n"
         else "",
         "  Until they are installed, run with summary_report = FALSE to skip the DOCX.",
         call. = FALSE)
  }
  if (!dir.exists(results_dir)) {
    stop("Results directory does not exist: ", results_dir, call. = FALSE)
  }
  out_dir <- safe_dir(out_dir)
  # One malformed results file must not cost the user the whole report: the
  # collection and every section builder are isolated, and any failure is
  # written both into the report and into report_warnings.txt.
  failures <- list()
  s <- tryCatch(collect_summary_data(cfg, results_dir),
                error = function(e) {
                  failures[["collect"]] <<- conditionMessage(e)
                  contrast <- cfg$analysis$contrasts[[1]]
                  list(contrast_name = contrast$name %||% "contrast",
                       contrast_label = paste0(contrast$numerator %||% "", " vs ",
                                               contrast$denominator %||% ""),
                       numerator = contrast$numerator %||% "",
                       denominator = contrast$denominator %||% "",
                       alpha = as.numeric(cfg$analysis$alpha %||% 0.05),
                       lfc = as.numeric(cfg$analysis$lfc_threshold %||% 0.75),
                       species = cfg$species$name %||% "—",
                       date = format(Sys.Date(), "%Y-%m-%d"))
                })
  s$ppi_score <- cfg$ppi$score_threshold %||% NA
  blocks <- lapply(template$sections, function(sec) {
    fn <- SUMMARY_BUILDERS[[sec$id]]
    content <- if (is.null(fn)) {
      list(paragraphs = character(0), tables = list())
    } else {
      tryCatch(fn(s), error = function(e) {
        failures[[sec$id]] <<- conditionMessage(e)
        list(paragraphs = sprintf(
          "This section could not be summarised from the available result files (%s). The remaining sections were written normally; re-run the analysis or inspect the files listed in report_warnings.txt.",
          conditionMessage(e)), tables = list())
      })
    }
    c(list(id = sec$id, title = sec$title, intro = sec$intro), content)
  })

  doc <- officer::read_docx()
  doc <- sr_add_par(doc, template$report_title, size = 22, bold = TRUE)
  doc <- sr_add_par(doc, sprintf("%s  |  %s  |  %s", s$contrast_label, s$species, s$date),
                    size = 11, colour = "grey35")
  doc <- sr_add_par(doc, "Prepared by ClawsGO Science Agent", size = 9, colour = "grey35")
  doc <- sr_add_par(doc, template$lead, size = 10)
  doc <- sr_add_par(doc, "", size = 4)

  # Number every table and appendix figure before writing, so the reading
  # guides can cite the same numbers that appear on the table and figure.
  caption_key <- function(x) sub("^Table [0-9]+\\.\\s*", "", x)
  table_numbers <- list(); table_no <- 0L
  for (b in blocks) {
    for (t in b$tables) {
      if (is.null(t$data) || !nrow(t$data)) next
      table_no <- table_no + 1L
      table_numbers[[caption_key(t$caption)]] <- table_no
    }
  }
  figs <- template$figures
  fig_paths <- vapply(figs, function(f) {
    file.path(results_dir, sprintf(f$file, s$contrast_name))
  }, character(1))
  keep <- file.exists(fig_paths)
  fig_numbers <- list(); fig_no <- 0L
  for (i in which(keep)) {
    fig_no <- fig_no + 1L
    fig_numbers[[figs[[i]]$key]] <- fig_no
  }

  table_no <- 0L
  for (b in blocks) {
    doc <- sr_add_heading(doc, b$title, size = 14)
    doc <- sr_add_par(doc, b$intro, size = 9.5, italic = TRUE, colour = "grey40")
    guide <- character(0)
    for (t in b$tables) {
      if (is.null(t$data) || !nrow(t$data)) next
      key <- caption_key(t$caption)
      guide <- c(guide, sprintf("Table %d, %s: %s.", table_numbers[[key]],
                                key, t$note))
    }
    for (key in SUMMARY_SECTION_FIGURES[[b$id]] %||% character(0)) {
      if (is.null(fig_numbers[[key]])) next
      f <- figs[[which(vapply(figs, function(x) identical(x$key, key), logical(1)))[1]]]
      guide <- c(guide, sprintf("Figure %d, %s It contains: %s",
                                fig_numbers[[key]], f$caption, f$content))
    }
    if (length(guide)) {
      doc <- sr_add_par(doc, paste0("Reading guide. ", paste(guide, collapse = " ")),
                        size = 9.5, italic = TRUE, colour = "grey35")
    }
    for (p in b$paragraphs) doc <- sr_add_par(doc, p, size = 10.5)
    for (t in b$tables) {
      if (is.null(t$data) || !nrow(t$data)) next
      table_no <- table_no + 1L
      caption <- caption_key(t$caption)
      doc <- sr_add_table(doc, sprintf("Table %d. %s", table_no, caption), t$data)
    }
    doc <- sr_add_par(doc, "", size = 4)
  }

  # --- appendix figures ------------------------------------------------------
  if (any(keep)) {
    doc <- officer::body_add_break(doc)
    doc <- sr_add_heading(doc, "Appendix. Key figures", size = 14)
    doc <- sr_add_par(doc, paste0("Each figure is introduced by its number, title and a description of the panels it contains. ",
                                  "The same figures are cited in the reading guide of the section that discusses them."),
                      size = 9.5, italic = TRUE, colour = "grey35")
    fig_no <- 0L
    for (i in which(keep)) {
      fig_no <- fig_no + 1L
      sz <- sr_img_size(fig_paths[i])
      doc <- tryCatch(officer::body_add_img(
        doc, src = fig_paths[i], width = sz[["width"]], height = sz[["height"]],
        style = "centered"), error = function(e) doc)
      doc <- sr_add_par(doc, sprintf("Figure %d. %s %s", fig_no, figs[[i]]$caption,
                                     figs[[i]]$content),
                        size = 8.5, colour = "grey35")
    }
  }

  out_path <- file.path(out_dir, file_name)
  print(doc, target = out_path)

  if (length(failures)) {
    writeLines(vapply(names(failures), function(k)
      sprintf("%s: %s", k, failures[[k]]), character(1)),
      file.path(out_dir, "report_warnings.txt"))
    warning("The report was written with ", length(failures),
            " section(s) missing; see report_warnings.txt", call. = FALSE)
  } else {
    unlink(file.path(out_dir, "report_warnings.txt"))
  }

  values <- summary_value_table(s, blocks)
  if (!is.null(values)) {
    utils::write.csv(values, file.path(out_dir, "summary_report_values.csv"),
                     row.names = FALSE, na = "")
  }
  write_status(file.path(out_dir, "status_summary.json"), "summary_report", "completed",
               NULL, list(file = basename(out_path), sections = length(blocks),
                          figures = sum(keep)))
  message("Summary report: ", out_path)
  invisible(out_path)
}
