sr_tbl <- function(caption, data) {
  key <- sub("^Table [0-9]+\\.\\s*", "", caption)
  note <- unname(SUMMARY_TABLE_NOTES[key])
  if (is.na(note)) note <- "the values summarised in the text above"
  list(caption = caption, data = data, note = note)
}

# Sentence describing the expression filters that shaped the tested gene set.
sr_expression_floor_note <- function(s) {
  parts <- character(0)
  if (isTRUE(s$fpkm_floor_applied)) {
    parts <- c(parts, sprintf(paste0(
      " The expression floor keeps the %s genes whose higher group-mean FPKM reaches %s, ",
      "so downstream screening and enrichment use that expressed universe; the count model is fitted before this floor."),
      sr_int(s$genes_above_floor), sr_num(s$min_fpkm, 0)))
  }
  if (is.numeric(s$expression_log10) && length(s$expression_log10) &&
      is.finite(s$expression_log10)) {
    parts <- c(parts, sprintf(paste0(
      " Genes with log10(mean normalized count) <= %s are excluded from the up/down classes ",
      "but remain in the result tables."), s$expression_log10))
  }
  paste(parts, collapse = "")
}

# ---------------------------------------------------------------------------
# Collect the results of one run
# ---------------------------------------------------------------------------
collect_summary_data <- function(cfg, results_dir) {
  contrast <- cfg$analysis$contrasts[[1]]
  contrast_name <- contrast$name %||% "contrast"
  contrast_label <- paste0(contrast$numerator %||% "", " vs ",
                           contrast$denominator %||% "")
  alpha <- as.numeric(cfg$analysis$alpha %||% 0.05)
  lfc <- as.numeric(cfg$analysis$lfc_threshold %||% 0.75)
  s <- list(
    contrast_name = contrast_name,
    contrast_label = contrast_label,
    numerator = contrast$numerator %||% "",
    denominator = contrast$denominator %||% "",
    species = cfg$species$name %||% cfg$species$common_name %||% "—",
    project = cfg$project$name %||% "bulk RNA-seq",
    counts_file = basename(cfg$input$counts_file %||% "—"),
    alpha = alpha, lfc = lfc,
    low_cutoff = cfg$analysis$low_cutoff %||% 0,
    up_cutoff = cfg$analysis$up_cutoff %||% NA_real_,
    p_adjust_method = cfg$analysis$p_adjust_method %||% "BH",
    shrinkage = cfg$analysis$lfc_shrinkage %||% "apeglm",
    min_count = cfg$analysis$min_count %||% NA,
    min_samples = cfg$analysis$min_samples %||% NA,
    expression_log10 = cfg$analysis$expression_log10_threshold %||% NA,
    min_fpkm = cfg$analysis$min_fpkm %||% 5,
    fpkm_floor_applied = local({
      f <- file.path(results_dir, "00_differential_expression", "expression_floor.csv")
      if (!file.exists(f)) return(FALSE)
      d <- tryCatch(utils::read.csv(f, stringsAsFactors = FALSE), error = record_optional_error)
      !is.null(d) && "kept" %in% names(d) && any(as.logical(d$kept) %in% TRUE)
    }),
    genes_above_floor = local({
      f <- file.path(results_dir, "00_differential_expression", "expression_floor.csv")
      if (!file.exists(f)) return(NA_integer_)
      d <- tryCatch(utils::read.csv(f, stringsAsFactors = FALSE), error = record_optional_error)
      if (is.null(d) || !"kept" %in% names(d)) NA_integer_ else sum(as.logical(d$kept) %in% TRUE)
    }),
    date = format(Sys.Date(), "%Y-%m-%d"))

  # --- sample groups ---------------------------------------------------------
  meta_file <- cfg$input$sample_metadata_file
  if (!is.null(meta_file) && file.exists(meta_file)) {
    meta <- tryCatch(utils::read.csv(meta_file, stringsAsFactors = FALSE),
                     error = record_optional_error)
    if (!is.null(meta) && nrow(meta)) {
      gcol <- cfg$analysis$group_column %||% "condition"
      s$n_samples <- nrow(meta)
      s$groups <- if (gcol %in% names(meta)) {
        tab <- table(meta[[gcol]])
        paste0(names(tab), " (n = ", as.integer(tab), ")", collapse = "; ")
      } else "—"
    }
  }

  # --- differential expression ----------------------------------------------
  de_dir <- file.path(results_dir, "00_differential_expression")
  de <- sr_read(de_dir, sr_pick(de_dir, "^DESeq2_.*_lfc_shrunk\\.csv$"))
  if (is.null(de)) de <- sr_read(de_dir, sr_pick(de_dir, "^DESeq2_.*\\.csv$"))
  if (!is.null(de)) {
    s$genes_tested <- nrow(de)
    s$genes_tested_label <- sr_int(nrow(de))
  }
  s1_dir <- file.path(results_dir, "section01_screening")
  s$class_summary <- sr_read(s1_dir, "S1_class_summary.csv")
  main_file <- sr_pick(s1_dir, sprintf("^S1_DEG_table_lfc_%s\\.csv$", format(lfc, nsmall = 2)))
  if (is.na(main_file)) main_file <- sr_pick(s1_dir, "^S1_DEG_table_lfc_1\\.00\\.csv$")
  s$deg_table <- sr_read(s1_dir, main_file)
  if (!is.null(s$class_summary) && nrow(s$class_summary)) {
    row <- s$class_summary[which.min(abs(sr_numvec(s$class_summary$lfc_limit) - lfc)), , drop = FALSE]
    s$n_up <- row$up[1]; s$n_down <- row$down[1]; s$n_deg <- row$total_degs[1]
    s$n_low_expression <- row$low_expression[1]
    s$n_not_significant <- row$not_significant[1]
  } else if (!is.null(s$deg_table)) {
    s$n_deg <- nrow(s$deg_table)
    s$n_up <- sum(s$deg_table$Direction == "Up", na.rm = TRUE)
    s$n_down <- sum(s$deg_table$Direction == "Down", na.rm = TRUE)
  }

  # --- GO --------------------------------------------------------------------
  go_dir <- file.path(results_dir, "section02_go_ora")
  s$go_summary <- sr_read(go_dir, "GO_ORA_summary.csv")
  s$go_terms <- list()
  for (ont in c("BP", "MF", "CC")) {
    f <- sr_pick(go_dir, sprintf("^ENRICHGO%ssignificant_%s\\.csv$", ont, s$contrast_name))
    if (is.na(f)) f <- sr_pick(go_dir, sprintf("^ENRICHGO%salls_%s\\.csv$", ont, s$contrast_name))
    tb <- sr_read(go_dir, f)
    if (!is.null(tb) && nrow(tb)) {
      p <- if (ont == "BP") cfg$analysis$go_bp_pvalue_cutoff else cfg$analysis$go_pvalue_cutoff
      q <- if (ont == "BP") cfg$analysis$go_bp_qvalue_cutoff else cfg$analysis$go_qvalue_cutoff
      keep <- is.finite(tb$pvalue) & tb$pvalue <= p & is.finite(tb$p.adjust) & tb$p.adjust <= p
      if ("qvalue" %in% names(tb) && any(is.finite(tb$qvalue)))
        keep <- keep & is.finite(tb$qvalue) & tb$qvalue <= q
      tb <- tb[keep, , drop = FALSE]
    }
    if (!is.null(tb) && nrow(tb)) {
      tb <- tb[order(tb$p.adjust, na.last = TRUE), , drop = FALSE]
      s$go_terms[[ont]] <- tb
    }
  }
  # Map the truncated set names used by section 9 back to the full term names.
  s$go_lookup <- unlist(lapply(names(s$go_terms), function(ont) {
    tb <- s$go_terms[[ont]]
    stats::setNames(tb$Description,
                    paste0("GO", ont, "_",
                           gsub("[^A-Za-z0-9]+", "_", substr(tb$Description, 1, 40))))
  }), use.names = TRUE)
  s$go_classes <- sr_read(go_dir, sr_pick(go_dir, "^GO_BP_functional_classes_.*\\.csv$"))

  # --- GSEA ------------------------------------------------------------------
  gsea_dir <- file.path(results_dir, "section03_gsea_go")
  s$gsea_summary <- sr_read(gsea_dir, "GSEA_GO_summary.csv")
  s$gsea_terms <- list()
  for (ont in c("BP", "MF", "CC")) {
    tb <- sr_read(gsea_dir, sr_pick(gsea_dir,
      sprintf("^GSEA_GO_%s_%s\\.csv$", ont, s$contrast_name)))
    if (!is.null(tb) && nrow(tb)) {
      tb <- tb[order(tb$p.adjust, na.last = TRUE), , drop = FALSE]
      s$gsea_terms[[ont]] <- tb
    }
  }
  s$msigdb <- sr_read(gsea_dir, sr_pick(gsea_dir, "^GSEA_MSigDB_.*\\.csv$"))

  # --- KEGG ------------------------------------------------------------------
  kegg_dir <- file.path(results_dir, "section04_kegg_pathview")
  s$kegg <- sr_read(kegg_dir, sr_pick(kegg_dir, "^KEGG_[A-Z].*\\.csv$"))
  if (!is.null(s$kegg) && nrow(s$kegg)) {
    s$kegg <- s$kegg[order(s$kegg$p.adjust, na.last = TRUE), , drop = FALSE]
  }

  # --- gene-set display ------------------------------------------------------
  gs_dir <- file.path(results_dir, "section09_geneset_heatmaps")
  s$genesets <- sr_read(gs_dir, "geneset_heatmap_summary.csv")

  # --- TF regulons -----------------------------------------------------------
  tf_dir <- file.path(results_dir, "section05_tf_regulon")
  s$tf <- sr_read(tf_dir, sr_pick(tf_dir, "^TF_regulon_summary_.*\\.csv$"))
  s$tf_edges <- sr_read(tf_dir, sr_pick(tf_dir, "^TF_target_edges_.*\\.csv$"))

  # --- TF / pathway activity -------------------------------------------------
  act_dir <- file.path(results_dir, "section06_regulatory_activity")
  s$activity <- list()
  for (m in c("ulm", "aucell", "wmean")) {
    tb <- sr_read(act_dir, sprintf("TF_activity_diff_%s.csv", m))
    if (!is.null(tb) && nrow(tb)) s$activity[[m]] <- tb
  }
  s$gsva <- sr_read(act_dir, paste0("GSVA_", cfg$pathway_activity$collection %||% "H", "_diff.csv"))
  s$activity_alpha <- cfg$regulatory$activity_alpha %||% s$alpha
  source_path <- file.path(act_dir, paste0("GSVA_", cfg$pathway_activity$collection %||% "H", "_source.json"))
  s$gsva_source <- if (file.exists(source_path)) jsonlite::read_json(source_path, simplifyVector = TRUE) else NULL

  # --- TF network, modules ---------------------------------------------------
  net_dir <- file.path(results_dir, "section07_tf_network")
  s$net_nodes <- sr_read(net_dir, sr_pick(net_dir, "^TF_network_nodes_.*\\.csv$"))
  s$net_edges <- sr_read(net_dir, sr_pick(net_dir, "^TF_network_edges_.*\\.csv$"))
  mod_dir <- file.path(results_dir, "section08_tf_modules")
  s$tf_modules <- sr_read(mod_dir, sr_pick(mod_dir, "^TF_cluster_modules_.*\\.csv$"))
  s$tf_members <- sr_read(mod_dir, sr_pick(mod_dir, "^TF_cluster_membership_.*\\.csv$"))

  # --- PPI -------------------------------------------------------------------
  ppi_dir <- file.path(results_dir, "section10_ppi_network")
  s$ppi_nodes <- sr_read(ppi_dir, sr_pick(ppi_dir, "^PPI_nodes_.*\\.csv$"))
  s$ppi_edges <- sr_read(ppi_dir, sr_pick(ppi_dir, "^PPI_edges_.*\\.csv$"))
  s$ppi_modules <- sr_read(ppi_dir, sr_pick(ppi_dir, "^PPI_modules_.*\\.csv$"))

  # --- subcellular -----------------------------------------------------------
  loc_dir <- file.path(results_dir, "section11_subcellular_localization")
  s$localization <- sr_read(loc_dir, sr_pick(loc_dir,
    sprintf("^subcellular_localization_%s\\.csv$", s$contrast_name)))
  s
}

