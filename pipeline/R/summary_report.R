summ_geneset <- function(s) {
  tabs <- list(); paras <- character(0)
  if (is.null(s$genesets) || !nrow(s$genesets)) {
    return(list(paragraphs = "No gene-set display result was available for this run.", tables = tabs))
  }
  tb <- s$genesets
  go <- tb[grepl("^GO", tb$set), , drop = FALSE]
  tf <- tb[grepl("^TF_", tb$set), , drop = FALSE]
  go_label <- function(x) {
    fallback <- gsub("_", " ", sub("^GO(BP|CC|MF)_", "", x))
    if (is.null(s$go_lookup)) return(fallback)
    full <- unname(s$go_lookup[x])
    ifelse(is.na(full), fallback, full)
  }
  if (nrow(go)) {
    tabs[[length(tabs) + 1L]] <- sr_tbl("GO gene sets shown as heat maps",
      data.frame(`Gene set` = go_label(go$set), `Genes displayed` = as.integer(go$members_found),
                 check.names = FALSE))
  }
  if (nrow(tf)) {
    tabs[[length(tabs) + 1L]] <- sr_tbl("TF regulons shown as dot plots",
      data.frame(`Regulon` = sub("^TF_", "", tf$set),
                 `Target genes displayed` = as.integer(tf$members_found), check.names = FALSE))
  }
  n_go <- nrow(go); n_tf <- nrow(tf)
  paras <- c(paras,
    sprintf("%s gene sets are displayed: %s GO terms as sample-level heat maps and %s TF regulons as expression-deviation dot plots.%s",
            sr_int(n_go + n_tf), sr_int(n_go), sr_int(n_tf),
            if (n_go) sprintf(" The GO terms are %s.", sr_join(go_label(go$set), 10L)) else ""))
  detail <- character(0)
  if (n_go) {
    detail <- c(detail, sprintf("Each GO heat map shows row-scaled expression of up to %s genes across the samples.",
                                sr_int(max(go$members_found, na.rm = TRUE))))
  }
  if (n_tf) {
    detail <- c(detail, sprintf("The TF regulons shown are %s; each dot plot shows expression level against deviation from the gene's row mean for up to %s target genes.",
                                sr_join(sub("^TF_", "", tf$set), 10L),
                                sr_int(max(tf$members_found, na.rm = TRUE))))
  }
  paras <- c(paras, paste(detail, collapse = " "))
  list(paragraphs = paras, tables = tabs)
}

summ_tf <- function(s) {
  tabs <- list(); paras <- character(0)
  if (is.null(s$tf) || !nrow(s$tf)) {
    return(list(paragraphs = "No TF regulon result was available for this run.", tables = tabs))
  }
  tb <- s$tf
  n_tested <- nrow(tb)
  n_ora <- sum(tb$padj < s$alpha, na.rm = TRUE)
  n_gsea <- sum(tb$gsea_padj < s$alpha, na.rm = TRUE)
  n_expressed <- if ("expressed" %in% names(tb)) sum(as.logical(tb$expressed), na.rm = TRUE) else NA
  expressed_label <- if (is.na(n_expressed)) "—" else sr_int(n_expressed)
  kv <- data.frame(
    `Item` = c("TFs tested", "Regulons significant by over-representation",
             "Regulons significant by GSEA", "TFs passing the expression filter",
             "Median DE targets per TF"),
    `Value` = c(sr_int(n_tested), sr_int(n_ora), sr_int(n_gsea), expressed_label,
              sr_num(stats::median(tb$targets_deg, na.rm = TRUE), 1)),
    check.names = FALSE)
  tabs[[length(tabs) + 1L]] <- sr_tbl("Table 14. TF regulon overview", kv)
  top <- utils::head(tb[order(-tb$targets_deg), , drop = FALSE], 12L)
  out <- data.frame(
    `TF` = top$tf, `DE targets` = as.integer(top$targets_deg),
    `Up / down` = paste0(top$targets_up, " / ", top$targets_down),
    `TF log2FC` = sr_num(top$tf_log2FC, 2),
    `Mean target log2FC` = sr_num(top$mean_target_log2FC, 2),
    `Leading GO BP` = sr_cut(vapply(top$top_GO_BP, sr_first, character(1)), 55),
    check.names = FALSE)
  tabs[[length(tabs) + 1L]] <- sr_tbl("Table 15. TFs with the largest number of differentially expressed targets", out)
  paras <- c(paras, sprintf("Of %s tested TFs, %s regulons are significant by over-representation and %s by regulon GSEA; %s TFs pass the expression filter (maximum group-mean FPKM >= %s) and are carried into the network and module sections. The median regulon contains %s differentially expressed targets.",
                            sr_int(n_tested), sr_int(n_ora), sr_int(n_gsea), expressed_label,
                            sr_num(s$min_fpkm, 0),
                            sr_num(stats::median(tb$targets_deg, na.rm = TRUE), 1)))
  if (nrow(top)) {
    paras <- c(paras, sprintf("The TFs with the largest target sets are %s, each with the number of differentially expressed targets in parentheses.",
                              sr_with_counts(top$tf, top$targets_deg, 10L)))
  }
  if (!is.null(s$tf_edges) && nrow(s$tf_edges)) {
    e <- s$tf_edges
    e <- e[as.logical(e$target_is_deg), , drop = FALSE]
    if (nrow(e)) {
      paras <- c(paras, sprintf("Across the tested regulons, the DE-target subnetwork contains %s TF-target edges, %s activating (positive mode of regulation) and %s repressing.",
                                sr_int(nrow(e)), sr_int(sum(e$mor > 0, na.rm = TRUE)),
                                sr_int(sum(e$mor < 0, na.rm = TRUE))))
      key_rows <- list()
      for (tf in utils::head(top$tf, 5L)) {
        x <- e[e$tf == tf, , drop = FALSE]
        if (!nrow(x)) next
        x <- x[order(-abs(sr_numvec(x$target_log2FC))), , drop = FALSE]
        x <- utils::head(x, 5L)
        key_rows[[length(key_rows) + 1L]] <- data.frame(
          `TF` = x$tf, `Key target` = x$target,
          `Direction` = ifelse(x$target_log2FC > 0, "Up", "Down"),
          `Target log2FC` = sr_num(x$target_log2FC, 2), check.names = FALSE)
      }
      if (length(key_rows)) {
        tabs[[length(tabs) + 1L]] <- sr_tbl(
          "Table 16. Key target genes of the five TFs with the largest regulons", do.call(rbind, key_rows))
        paras <- c(paras, sprintf("The key-target table lists the five targets with the largest absolute log2 fold change for each of %s.",
                                  sr_join(utils::head(top$tf, 5L), 5L)))
      }
    }
  }
  list(paragraphs = paras, tables = tabs)
}

summ_activity <- function(s) {
  tabs <- list(); paras <- character(0)
  labels <- c(ulm = "ULM", aucell = "AUCell", wmean = "Weighted mean")
  rows <- list()
  for (m in names(s$activity)) {
    tb <- s$activity[[m]]
    sig <- tb[!is.na(tb$padj) & tb$padj < (s$activity_alpha %||% s$alpha), , drop = FALSE]
    up <- sum(sig$difference > 0, na.rm = TRUE); dn <- sum(sig$difference < 0, na.rm = TRUE)
    paras <- c(paras, sprintf("%s identifies %s TFs with differential activity (%s higher and %s lower in %s).",
                              labels[[m]], sr_int(nrow(sig)), sr_int(up), sr_int(dn), s$numerator))
    if ("test_status" %in% names(tb)) {
      unavailable <- tb[tb$test_status != "tested", , drop = FALSE]
      if (nrow(unavailable)) paras <- c(paras, sprintf(
        "%s retains %s profiles without a valid Welch test (%s). Their group means and differences are reported; P values are NA. Reasons are recorded in the differential-activity table.",
        labels[[m]], sr_int(nrow(unavailable)), sr_join(unavailable$source, 10L)))
    }
    top <- sig[order(-abs(sr_numvec(sig$difference))), , drop = FALSE]
    top <- utils::head(top, 5L)
    if (nrow(top)) {
      rows[[length(rows) + 1L]] <- data.frame(
        `Method` = labels[[m]], `TF` = top$source,
        `Activity difference` = sr_num(top$difference, 2), `Adjusted P` = sr_p(top$padj),
        check.names = FALSE)
      paras <- c(paras, sprintf("The strongest %s changes are %s.",
                                labels[[m]], sr_join(paste0(top$source, " (", sr_num(top$difference, 2), ")"), 5L)))
    }
  }
  if (length(rows)) tabs[[length(tabs) + 1L]] <- sr_tbl(
    "Table 17. Strongest differential TF activity by method", do.call(rbind, rows))
  if (!is.null(s$gsva) && nrow(s$gsva)) {
    if (!is.null(s$gsva_source)) paras <- c(paras, sprintf(
      "GSVA gene sets: MSigDB %s, database %s, collection %s, target species %s; ortholog mapping: %s.",
      paste(s$gsva_source$database_version, collapse = "/"), s$gsva_source$database,
      s$gsva_source$collection, s$gsva_source$target_species,
      if (isTRUE(s$gsva_source$ortholog_mapping)) "yes" else "no"))
    tb <- s$gsva[!is.na(s$gsva$padj) & s$gsva$padj < (s$activity_alpha %||% s$alpha), , drop = FALSE]
    paras <- c(paras, sprintf("GSVA of the Hallmark collection finds %s pathways with differential activity, %s higher and %s lower in %s.",
                              sr_int(nrow(tb)), sr_int(sum(tb$difference > 0, na.rm = TRUE)),
                              sr_int(sum(tb$difference < 0, na.rm = TRUE)), s$numerator))
    top <- tb[order(-abs(sr_numvec(tb$difference))), , drop = FALSE]
    top <- utils::head(top, 8L)
    if (nrow(top)) {
      tabs[[length(tabs) + 1L]] <- sr_tbl("Table 18. Strongest differential pathway activity (GSVA)",
        data.frame(`Pathway` = gsub("^HALLMARK_", "", top$source),
                   `Activity difference` = sr_num(top$difference, 2), `Adjusted P` = sr_p(top$padj),
                   check.names = FALSE))
      paras <- c(paras, sprintf("The most changed pathways are %s.",
                                sr_join(gsub("^HALLMARK_", "", top$source), 8L)))
    }
  }
  if (!length(paras)) paras <- "No activity result was available for this run."
  list(paragraphs = paras, tables = tabs)
}

summ_network <- function(s) {
  tabs <- list(); paras <- character(0)
  if (is.null(s$net_nodes) || !nrow(s$net_nodes)) {
    return(list(paragraphs = "No TF network result was available for this run.", tables = tabs))
  }
  nd <- s$net_nodes
  is_tf <- as.logical(nd$is_tf)
  n_tf <- sum(is_tf, na.rm = TRUE); n_gene <- sum(!is_tf, na.rm = TRUE)
  n_edge <- if (!is.null(s$net_edges)) nrow(s$net_edges) else NA
  n_act <- if (!is.null(s$net_edges) && "mor" %in% names(s$net_edges))
    sum(s$net_edges$mor > 0, na.rm = TRUE) else NA
  n_rep <- if (!is.null(s$net_edges) && "mor" %in% names(s$net_edges))
    sum(s$net_edges$mor < 0, na.rm = TRUE) else NA
  kv <- data.frame(`Item` = c("TFs in the network", "Target-gene nodes", "Edges",
                            "Activating / repressing edges"),
                   `Value` = c(sr_int(n_tf), sr_int(n_gene), sr_int(n_edge),
                            sprintf("%s / %s", sr_int(n_act), sr_int(n_rep))),
                   check.names = FALSE)
  tabs[[length(tabs) + 1L]] <- sr_tbl("Table 19. TF-target network size", kv)
  tfs <- nd$name[is_tf]
  paras <- c(paras, sprintf("The network contains %s TFs, %s target genes and %s edges; %s edges activate and %s repress their target. The TFs are %s.",
                            sr_int(n_tf), sr_int(n_gene), sr_int(n_edge), sr_int(n_act), sr_int(n_rep),
                            sr_join(tfs, 25L)))
  targets <- nd[!is_tf, , drop = FALSE]
  if (nrow(targets)) {
    targets <- targets[order(-abs(suppressWarnings(as.numeric(targets$lfc)))), , drop = FALSE]
    paras <- c(paras, sprintf("The target genes with the largest expression change in the network are %s.",
                              sr_with_counts(targets$name, as.numeric(targets$lfc), 10L, 2L)))
  }
  if (!is.null(s$net_edges) && nrow(s$net_edges)) {
    e <- s$net_edges
    deg_tab <- sort(table(e$tf), decreasing = TRUE)
    if (length(deg_tab)) {
      paras <- c(paras, sprintf("By out-degree the central TFs are %s.",
                                sr_with_counts(names(deg_tab), as.numeric(deg_tab), 10L)))
    }
  }
  list(paragraphs = paras, tables = tabs)
}

summ_modules <- function(s) {
  tabs <- list(); paras <- character(0)
