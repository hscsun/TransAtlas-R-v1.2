sr_add_par <- function(doc, text, size = 10.5, bold = FALSE, italic = FALSE,
                       colour = "grey15", style = NULL, keep = FALSE) {
  fpar <- officer::fpar(
    officer::ftext(
      text, officer::fp_text(font.family = "Times New Roman", font.size = size,
                             bold = bold, italic = italic, color = colour)),
    fp_p = officer::fp_par(keep_with_next = keep, word_style = "Normal"))
