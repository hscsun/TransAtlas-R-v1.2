              sprintf("BH-adjusted P < %s; |log2FC| >= %s", s$alpha, s$lfc),
              s$p_adjust_method, s$shrinkage,
              if (is.numeric(s$min_fpkm) && is.finite(s$min_fpkm) &&
                    !identical(s$fpkm_floor_applied, FALSE))
                sprintf("max group-mean FPKM >= %s (%s of %s tested genes kept)",
                        s$min_fpkm, sr_int(s$genes_above_floor), s$genes_tested_label %||% "—")
              else if (is.numeric(s$expression_log10) && is.finite(s$expression_log10))
                sprintf("log10(mean normalized count) > %s", s$expression_log10) else "none",
              s$genes_tested_label %||% "—",
              sprintf("%s (%s / %s)", sr_int(s$n_deg), sr_int(s$n_up), sr_int(s$n_down))),
    check.names = FALSE, stringsAsFactors = FALSE)
  paras <- c(
    sprintf("The analysis compares %s against %s across %s samples in %s groups (%s). Counts were modelled with a negative-binomial GLM and tested with the Wald test; P values were adjusted by the %s procedure. Separate inspection tables contain effects shrunk with %s; downstream calculations use unshrunk estimates.",
            s$numerator, s$denominator, sr_int(s$n_samples %||% NA), sr_int(length(strsplit(s$groups %||% "", ";")[[1]])),
            s$groups %||% "—", s$p_adjust_method, s$shrinkage),
    sprintf("A gene is called differentially expressed when its adjusted P value is below %s and the absolute unshrunk log2 fold change reaches %s.%s",
            s$alpha, s$lfc, sr_expression_floor_note(s)),
    sprintf("GSEA uses genes with BH-adjusted P < %s and absolute unshrunk log2 fold change >= %s, ranked by their true effect without upper clipping. The screening ladder does not set this lower bound. The display-only upper limit is %s; calculation tables retain true effects.",
            s$alpha, s$low_cutoff, if (is.finite(s$up_cutoff)) paste0("+/-", s$up_cutoff) else "automatic"))
  list(paragraphs = paras, tables = list(sr_tbl("Table 1. Run design and group composition", kv)))
}

summ_deg <- function(s) {
  tabs <- list(); paras <- character(0)
  if (!is.null(s$class_summary) && nrow(s$class_summary)) {
    tb <- s$class_summary
    out <- data.frame(
      `|log2FC| threshold` = tb$lfc_limit,
      `Up-regulated` = as.integer(tb$up),
      `Down-regulated` = as.integer(tb$down),
      `Total` = as.integer(tb$total_degs),
      check.names = FALSE)
    tabs[[length(tabs) + 1L]] <- sr_tbl("Table 2. Differentially expressed genes at each fold-change threshold", out)
    counts <- sprintf("%s at |log2FC| >= %s", sr_int(tb$total_degs), format(tb$lfc_limit, trim = TRUE))
    paras <- c(paras, sprintf("The number of DEGs rises smoothly as the fold-change threshold is relaxed: %s.",
                              sr_join(counts, 8L)))
  }
  key <- NULL
  if (!is.null(s$deg_table) && nrow(s$deg_table)) {
    tb <- s$deg_table
    tb$abs_lfc <- abs(suppressWarnings(as.numeric(tb$GenesFoldChange_raw)))
    tb$base <- suppressWarnings(as.numeric(tb$GenesbaseMean))
    up <- tb[tb$Direction == "Up", , drop = FALSE]
    dn <- tb[tb$Direction == "Down", , drop = FALSE]
    up_eff <- utils::head(up[order(-up$abs_lfc), , drop = FALSE], 5L)
    dn_eff <- utils::head(dn[order(-dn$abs_lfc), , drop = FALSE], 5L)
    up_exp <- utils::head(up[order(-up$base), , drop = FALSE], 5L)
    dn_exp <- utils::head(dn[order(-dn$base), , drop = FALSE], 5L)
    key <- rbind(utils::head(up[order(-up$abs_lfc), , drop = FALSE], 8L),
                 utils::head(dn[order(-dn$abs_lfc), , drop = FALSE], 8L))
    if (nrow(key)) {
      key_out <- data.frame(
        `Gene` = key$GenesSymbol,
        `Direction` = ifelse(key$Direction == "Up", "Up", "Down"),
        `log2FC` = sr_num(key$GenesFoldChange_raw, 2),
        `Mean normalized count` = sr_num(key$GenesbaseMean, 1),
        `Adjusted P` = sr_p(key$GenesQvalue),
        check.names = FALSE)
      tabs[[length(tabs) + 1L]] <- sr_tbl(
        "Table 3. Genes with the largest effect size (eight up and eight down)", key_out)
    }
    if (nrow(up_eff) && nrow(dn_eff)) {
      eff_tab <- data.frame(
        `Direction` = c(rep("Up", nrow(up_eff)), rep("Down", nrow(dn_eff))),
        `Gene` = c(up_eff$GenesSymbol, dn_eff$GenesSymbol),
        `log2FC` = sr_num(c(up_eff$GenesFoldChange_raw, dn_eff$GenesFoldChange_raw), 2),
        `Adjusted P` = sr_p(c(up_eff$GenesQvalue, dn_eff$GenesQvalue)),
        check.names = FALSE)
      tabs[[length(tabs) + 1L]] <- sr_tbl(
        "Table 4. Five strongest up- and down-regulated genes by |log2FC|", eff_tab)
      exp_tab <- data.frame(
        `Direction` = c(rep("Up", nrow(up_exp)), rep("Down", nrow(dn_exp))),
        `Gene` = c(up_exp$GenesSymbol, dn_exp$GenesSymbol),
        `Mean normalized count` = sr_num(c(up_exp$GenesbaseMean, dn_exp$GenesbaseMean), 1),
        `log2FC` = sr_num(c(up_exp$GenesFoldChange_raw, dn_exp$GenesFoldChange_raw), 2),
        check.names = FALSE)
      tabs[[length(tabs) + 1L]] <- sr_tbl(
        "Table 5. Five most highly expressed up- and down-regulated genes", exp_tab)
    }
  }
  paras <- c(paras, sprintf("At the primary threshold (adjusted P < %s, |log2FC| >= %s) there are %s DEGs: %s up-regulated and %s down-regulated, a ratio of %.2f to 1. %s genes remain in the low-expression class and %s did not reach significance.",
                            s$alpha, s$lfc, sr_int(s$n_deg), sr_int(s$n_up), sr_int(s$n_down),
                            (as.numeric(s$n_up) + 0.5) / (as.numeric(s$n_down) + 0.5),
                            sr_int(s$n_low_expression %||% NA), sr_int(s$n_not_significant %||% NA)))
  if (!is.null(key) && nrow(key)) {
    up_names <- key$GenesSymbol[key$Direction == "Up"]
    dn_names <- key$GenesSymbol[key$Direction == "Down"]
    paras <- c(paras,
      sprintf("The strongest up-regulated genes by effect size are %s. The strongest down-regulated genes are %s.",
              sr_join(up_names, 8L), sr_join(dn_names, 8L)),
      sprintf("Ranked by expression rather than effect, the most abundant up-regulated DEGs are %s, and the most abundant down-regulated DEGs are %s. These genes combine a large absolute change with a high baseline count and are therefore the most reliable candidates for targeted validation.",
              sr_join(up_exp$GenesSymbol, 5L),
              sr_join(dn_exp$GenesSymbol, 5L)))
  }
  list(paragraphs = paras, tables = tabs)
}

summ_go <- function(s) {
  tabs <- list(); paras <- character(0)
  if (!is.null(s$go_summary) && nrow(s$go_summary)) {
    g <- s$go_summary
    out <- data.frame(
      `Ontology` = g$ontology,
      `Significant terms` = as.integer(g$terms),
      `After semantic simplification` = as.integer(g$terms_simplified),
      check.names = FALSE)
    tabs[[length(tabs) + 1L]] <- sr_tbl("Table 6. Significant GO terms per ontology", out)
    paras <- c(paras, sprintf("Over-representation analysis of the DEGs returns %s significant biological-process terms, %s molecular-function terms and %s cellular-component terms (adjusted P < %s). Semantic simplification retains %s, %s and %s terms respectively, removing parent-child redundancy while keeping the leading functions.",
                              sr_int(g$terms[g$ontology == "BP"]), sr_int(g$terms[g$ontology == "MF"]),
                              sr_int(g$terms[g$ontology == "CC"]), s$alpha,
                              sr_int(g$terms_simplified[g$ontology == "BP"]),
                              sr_int(g$terms_simplified[g$ontology == "MF"]),
                              sr_int(g$terms_simplified[g$ontology == "CC"])))
  }
  top <- list()
  for (ont in names(s$go_terms)) {
    tb <- s$go_terms[[ont]]
    if (!nrow(tb)) next
    tab <- utils::head(tb, 10L)
    top[[ont]] <- data.frame(
      `Ontology` = ont, `Leading term` = tab$Description,
      `Genes` = as.integer(tab$Count), `Adjusted P` = sr_p(tab$p.adjust),
      check.names = FALSE)
    leading <- utils::head(tb, 10L)
    if (nrow(leading)) {
      paras <- c(paras, sprintf("The leading %s terms, with the number of DEGs annotated to each, are %s.",
                                ont, sr_with_counts(leading$Description, leading$Count, 10L)))
    }
  }
  if (length(top)) {
    tabs[[length(tabs) + 1L]] <- sr_tbl(
      "Table 7. Leading GO terms in each ontology", do.call(rbind, top))
  }
  if (!is.null(s$go_classes) && nrow(s$go_classes)) {
    cl <- s$go_classes
    agg <- lapply(sort(unique(cl$class)), function(g) {
      x <- cl[cl$class == g, , drop = FALSE]
      data.frame(`Functional class` = paste0("C", g), `Representative term` = x$class_representative[1],
                 `Terms` = nrow(x), `Genes in representative term` = as.integer(x$Count[1]),
                 check.names = FALSE)
    })
    agg <- do.call(rbind, agg)
    tabs[[length(tabs) + 1L]] <- sr_tbl("Table 8. Functional classes of the GO biological-process result", agg)
    paras <- c(paras, sprintf("Clustering the BP terms by semantic similarity groups them into %s functional classes. The classes and their representative terms are %s. Together these classes describe the biological programme behind the expression change rather than a flat list of terms.",
                              sr_int(nrow(agg)),
                              sr_join(paste0(agg$`Functional class`, " (", agg$`Representative term`, ")"), 10L)))
    if (!is.null(s$go_terms$BP) && nrow(s$go_terms$BP)) {
      paras <- c(paras, sprintf("The single most significant BP term is %s, annotated to %s DEGs (adjusted P = %s). The next terms are %s.",
                                s$go_terms$BP$Description[1], sr_int(s$go_terms$BP$Count[1]),
                                sr_p(s$go_terms$BP$p.adjust[1]),
                                sr_with_counts(utils::head(s$go_terms$BP$Description, 6L)[-1],
                                               utils::head(s$go_terms$BP$Count, 6L)[-1], 5L)))
    }
  }
  list(paragraphs = paras, tables = tabs)
}

summ_gsea <- function(s) {
  tabs <- list(); paras <- character(0)
  if (!is.null(s$gsea_summary) && nrow(s$gsea_summary)) {
    g <- s$gsea_summary
    out <- data.frame(`Ontology` = g$ontology, `Significant gene sets` = as.integer(g$sets_significant),
                      `Activated` = as.integer(g$up), `Repressed` = as.integer(g$down),
                      check.names = FALSE)
    tabs[[length(tabs) + 1L]] <- sr_tbl("Table 9. Significant GSEA gene sets and their direction", out)
    paras <- c(paras, sprintf("GSEA over the screened ranked list identifies %s activated and %s repressed biological-process gene sets. Molecular-function and cellular-component collections contribute %s and %s significant sets, of which %s and %s are repressed.",
                              sr_int(g$up[g$ontology == "BP"]), sr_int(g$down[g$ontology == "BP"]),
